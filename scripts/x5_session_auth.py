# 54-A: the recipe is declared in the plugin source/config and documented
# ---------------------------------------------------------------------------
def check_recipe_static():
    if not plugin_installed():
        return skip("mcp-playwright not installed (other stack) - nothing to test")
    # the committed deliverable (omni-plugins source)
    if os.path.exists(CFG_SRC):
        src = open(CFG_SRC, encoding="utf-8").read()
        for needle in WRAPPER_NEEDLES:
            assert needle in src, f"plugin SOURCE mcp-config.json misses {needle!r}"
    if os.path.exists(README_SRC):
        rd = open(README_SRC, encoding="utf-8").read().lower()
        for needle in README_NEEDLES:
            assert needle in rd, \
                f"plugin SOURCE README misses the X5 recipe statement {needle!r}"
    # the config that is actually deployed (also carries the $secret: env ref)
    cfg = open(CFG, encoding="utf-8").read()
    for needle in WRAPPER_NEEDLES + ("$secret:",):
        assert needle in cfg, f"deployed wrapper config misses {needle!r}"
    # The profile skill that documents the recipe is a hand-authored profile
    # file: another setup may legitimately not ship it. Assert its content when
    # it is present (a shipped skill that lost the recipe is still a failure)
    # and SKIP instead of failing on the fixed path when it is absent, so the
    # group stays setup-agnostic (no hard dependency on a profiles/... fixture
    # existing). The skill LOAD path is asserted behaviourally elsewhere
    # (tests.py group 45-A seeds a skill and asserts the skills tool loads it).
    if os.path.exists(SKILL):
        sk = open(SKILL, encoding="utf-8").read()
        for needle in SKILL_NEEDLES:
            assert needle in sk, \
                f"web-interaction skill misses the X5 recipe statement {needle!r}"
        skill_note = "the web-interaction skill carries it too"
    else:
        skip(f"profile skill {SKILL} is absent in this setup (setup-agnostic) - "
             "the skill content assertions are skipped")
        skill_note = (f"the web-interaction skill is absent in this setup "
                      f"({SKILL}) - content check skipped")
    assert os.path.isdir(STATE_DIR), f"state dir missing: {STATE_DIR}"
    gi = f"{OMNI_DIR}/.gitignore"
    gi_txt = open(gi, encoding="utf-8").read() if os.path.exists(gi) else ""
    assert re.search(r"(?m)^/?data/?\s*$", gi_txt), \
        "the omni dir does not gitignore the data/ dir holding the state files"
    print("PASS: 54-A plugin source + deployed wrapper declare per-site "
          "--storage-state and --secrets (secrets by name), state lives under the "
          "gitignored data dir; the README carries the "
          "login-once/reuse/redact/cookie-hygiene/no-blind-retry recipe; "
          f"{skill_note}")


# ---------------------------------------------------------------------------
# 54-B: login once, save the storage state, reuse it in a NEW process
# ---------------------------------------------------------------------------
def check_storage_state_roundtrip():
    if not plugin_installed():
        return skip("mcp-playwright not installed (other stack) - nothing to test")
    if not ensure_fixture():
        raise AssertionError("could not start the self-contained browser fixture site")
    state = "x5-t54-roundtrip.json"
    path = f"{STATE_DIR}/{state}"
    if os.path.exists(path):
        os.remove(path)
    s1 = Session({"PW_STATE_FILE": state}, "54-B run1")
    try:
        nav = s1.call("browser_navigate", {"url": f"{SITE}/login.html"}, 180)
        assert nav["ok"], f"run1 navigate failed: {nav['text'][:300]}"
        s1.call("browser_type", {"target": "#user", "text": DEMO_USER}, 120)
        s1.call("browser_type", {"target": "#pass", "text": DEMO_PASS}, 120)
        click = s1.call("browser_click", {"target": "#submit"}, 180)
        assert click["ok"], f"run1 login click failed: {click['text'][:300]}"
        body = snapshot_text(s1).lower()
        assert "logged in successfully" in body, \
            f"run1 login did not reach the account page: {body[:300]}"
        save = s1.call("browser_run_code_unsafe", {"code": (
            "async (page) => { await page.context().storageState("
            f"{{ path: '/pw/state/{state}' }}); return 'storage state saved'; }}" )}, 120)
        assert save["ok"], f"saving the storage state failed: {save['text'][:300]}"
        assert state in save["text"] or "storage state saved" in save["text"], \
            f"unexpected save result: {save['text'][:200]}"
        s1.call("browser_close", {}, 60)
    finally:
        s1.close()

    assert os.path.exists(path), f"run1 did not write the per-site state file {path}"
    blob = open(path, encoding="utf-8").read()
    assert "cookies" in blob and "host.docker.internal" in blob, \
        f"the saved state has no cookies for the site: {blob[:200]}"

    s2 = Session({"PW_STATE_FILE": state}, "54-B run2")
    try:
        nav2 = s2.call("browser_navigate", {"url": f"{SITE}/index.html"}, 180)
        assert nav2["ok"], f"run2 navigate failed: {nav2['text'][:300]}"
        body2 = snapshot_text(s2).lower()
        assert "logged in successfully" in body2, \
            f"run2 (no login step) is not authenticated - state not reused: {body2[:300]}"
        assert "login required" not in body2, \
            f"run2 showed the anonymous page although a state file was supplied: {body2[:300]}"
    finally:
        s2.close()
    print(f"PASS: 54-B login once -> {state} saved (session cookie for the site) -> a "
          "FRESH MCP process with the same PW_STATE_FILE landed on the account page "
          "with no login step at all (session reused, not re-authenticated)")


# ---------------------------------------------------------------------------
# 54-C: --secrets redaction keeps the raw value out of every tool response
# ---------------------------------------------------------------------------
def check_secrets_redaction():
    if not plugin_installed():
        return skip("mcp-playwright not installed (other stack) - nothing to test")
    if not ensure_fixture():
        raise AssertionError("could not start the self-contained browser fixture site")
    val = ensure_secret(SECRET_NAME)
    s = Session({"PW_STATE_FILE": "x5-t54-redact.json",
                 "PW_SECRET_" + SECRET_NAME: val}, "54-C")
    try:
        assert s.call("browser_navigate", {"url": f"{SITE}/login.html"}, 180)["ok"]
        res = s.call("browser_type", {"target": "#user", "text": val}, 120)
        assert res["ok"], f"type with the secret value failed: {res['text'][:300]}"
        assert val not in res["text"], \
            "RAW secret value leaked into the tool response (redaction broken)"
        assert f"<secret>{SECRET_NAME}</secret>" in res["text"], \
            f"the value was not replaced by the redaction placeholder: {res['text'][:300]}"
    finally:
        s.close()
    envf = f"{STATE_DIR}/secrets.env"
    assert os.path.exists(envf), "the wrapper did not write the --secrets dotenv"
    mode = oct(os.stat(envf).st_mode & 0o777)
    assert mode in ("0o600", "0o640", "0o644"), f"secrets.env mode {mode} is too open"
    for p in (CFG, README_DEPLOYED, README_SRC, CFG_SRC, SKILL):
        if os.path.exists(p):
            assert val not in open(p, encoding="utf-8").read(), \
                f"the secret value is present in {p} (must stay in the store only)"
    print(f"PASS: 54-C --secrets redaction: the value from the secrets store came back "
          f"as <secret>{SECRET_NAME}</secret> in the tool response, never raw; "
          f"secrets.env {mode} under the gitignored state dir; no literal in "
          "config/README/skill")


# ---------------------------------------------------------------------------
# 54-D: negative control -- an empty state file grants nothing
# ---------------------------------------------------------------------------
def check_negative_control():
    if not plugin_installed():
        return skip("mcp-playwright not installed (other stack) - nothing to test")
    if not ensure_fixture():
        raise AssertionError("could not start the self-contained browser fixture site")
    state = "x5-t54-empty.json"
    path = f"{STATE_DIR}/{state}"
    with open(path, "w", encoding="utf-8") as fh:
        fh.write('{"cookies":[],"origins":[]}')
    s = Session({"PW_STATE_FILE": state}, "54-D")
    try:
        nav = s.call("browser_navigate", {"url": f"{SITE}/index.html"}, 180)
        assert nav["ok"], f"navigate failed: {nav['text'][:300]}"
        body = snapshot_text(s).lower()
        assert "login required" in body, \
            f"expected the anonymous page with an empty state file: {body[:300]}"
        assert "logged in successfully" not in body, \
            "an EMPTY state file granted access - 54-B would be vacuous"
    finally:
        s.close()
    st = os.stat(path)
    if st.st_uid == 1000:
        assert oct(st.st_mode & 0o777) == "0o600", \
            f"state file mode {oct(st.st_mode & 0o777)} (wrapper keeps 700/600)"
    print("PASS: 54-D empty state file -> the account page shows 'Login required' "
          "(access comes from the saved session, not from the browser being open)")


CHECKS = {
    "54a": check_recipe_static,
    "54b": check_storage_state_roundtrip,
    "54c": check_secrets_redaction,
    "54d": check_negative_control,
}


def main(argv):
    only = None
    if "--only" in argv:
        only = set(argv[argv.index("--only") + 1].split(","))
    failed = 0
    for key, fn in CHECKS.items():
        if only and key not in only:
            continue
        try:
            fn()
        except AssertionError as e:
            print(f"FAIL: {key}: {e}")
            failed += 1
        except Exception as e:  # noqa: BLE001 - the runner turns it into a failed test
            print(f"FAIL: {key}: {type(e).__name__}: {e}")
            failed += 1
    print(json.dumps({"group": 54, "failed": failed}))
    return 1 if failed else 0


if __name__ == "__main__":
    sys_exit = main([a for a in os.sys.argv[1:]])
    fixture_down()
    raise SystemExit(sys_exit)
