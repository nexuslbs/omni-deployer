# secrets store (values are never printed, logged or written into a repo file)
# ---------------------------------------------------------------------------
def _api(path, data=None, method="GET"):
    req = urllib.request.Request(
        f"{BASE}{path}",
        data=json.dumps(data).encode() if data is not None else None,
        headers={"Content-Type": "application/json"}, method=method)
    try:
        with urllib.request.urlopen(req, timeout=15) as r:
            return json.loads(r.read().decode() or "{}")
    except urllib.error.HTTPError as e:
        if e.code in (404, 409):
            return None
        raise


def secret_value(name):
    body = _api(f"/secrets/{name}")
    if not body:
        return None
    return (body.get("data") or {}).get("current_value") or None


def ensure_secret(name):
    val = secret_value(name)
    if val:
        return val
    val = "".join(secrets.choice(string.ascii_letters + string.digits)
                  for _ in range(24))
    _api("/secrets", {"name": name, "fieldType": "password", "value": val}, "POST")
    val = secret_value(name)
    assert val, f"could not create the secret {name} via {BASE}/secrets"
    return val


# ---------------------------------------------------------------------------
# MCP stdio driver (one child process = one browser session)
# ---------------------------------------------------------------------------
def _read_dotenv(path):
    values = {}
    try:
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                k, v = line.split("=", 1)
                if v:
                    values[k.strip()] = v
    except FileNotFoundError:
        pass
    return values


class Session:
    """Spawn the deployed mcp-playwright wrapper and speak JSON-RPC on stdio."""

    def __init__(self, env, label):
        self.label = label
        srv = json.load(open(CFG, encoding="utf-8"))["servers"][0]
        child_env = {"PATH": os.environ.get(
            "PATH", "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin")}
        child_env.update(env or {})
        self.proc = subprocess.Popen(
            [srv["command"]] + srv["args"], stdin=subprocess.PIPE,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            env=child_env, text=True, bufsize=1)
        self.q = queue.Queue()
        for stream, tag in ((self.proc.stdout, "out"), (self.proc.stderr, "err")):
            threading.Thread(target=self._pump, args=(stream, tag), daemon=True).start()
        self.rid = 1
        self._send({"jsonrpc": "2.0", "id": self.rid, "method": "initialize",
                    "params": {"protocolVersion": "2024-11-05", "capabilities": {},
                               "clientInfo": {"name": "x5-session-auth", "version": "1.0"}}})
        msg, extra = self._wait(self.rid, 180)
        assert msg is not None, f"{label}: MCP initialize failed ({extra[-3:]})"
        self._send({"jsonrpc": "2.0", "method": "notifications/initialized", "params": {}})
        # the wrapper writes the --secrets dotenv before it execs the browser
        self.secret_values = _read_dotenv(f"{STATE_DIR}/secrets.env")

    def _pump(self, stream, tag):
        try:
            for line in stream:
                self.q.put((tag, line))
        except Exception:
            pass

    def _send(self, obj):
        self.proc.stdin.write(json.dumps(obj) + "\n")
        self.proc.stdin.flush()

    def _wait(self, rid, timeout):
        deadline = time.time() + timeout
        extra = []
        while time.time() < deadline:
            try:
                tag, line = self.q.get(timeout=max(0.1, deadline - time.time()))
            except queue.Empty:
                break
            line = line.rstrip("\n")
            if tag == "err":
                extra.append("[stderr] " + line)
                continue
            if not line.strip():
                continue
            try:
                msg = json.loads(line)
            except Exception:
                extra.append("[raw] " + line)
                continue
            if msg.get("id") == rid:
                return msg, extra
            extra.append(line)
        if self.proc.poll() is not None:
            extra.append(f"[wrapper exited rc={self.proc.returncode}]")
        return None, extra

    def call(self, tool, arguments=None, timeout=180):
        self.rid += 1
        self._send({"jsonrpc": "2.0", "id": self.rid, "method": "tools/call",
                    "params": {"name": tool,
                               "arguments": self._substitute(arguments or {})}})
        msg, extra = self._wait(self.rid, timeout)
        assert msg is not None, f"{self.label}: {tool} timed out ({extra[-3:]})"
        result = msg.get("result") or {}
        content = result.get("content") or []
        text = "\n".join(c.get("text", "") for c in content if isinstance(c, dict))
        if not text and msg.get("error"):
            text = json.dumps(msg["error"])
        ok = not msg.get("error") and not result.get("isError")
        return {"tool": tool, "ok": ok, "text": text}

    def _substitute(self, node):
        if isinstance(node, str):
            return PLACEHOLDER.sub(
                lambda m: self.secret_values.get(m.group(1), m.group(0)), node)
        if isinstance(node, list):
            return [self._substitute(x) for x in node]
        if isinstance(node, dict):
            return {k: self._substitute(v) for k, v in node.items()}
        return node

    def close(self):
        try:
            self.proc.stdin.close()
        except Exception:
            pass
        self.proc.terminate()
        try:
            self.proc.wait(timeout=15)
        except Exception:
            self.proc.kill()


def snapshot_text(session):
    snap = session.call("browser_snapshot", {}, 120)
    return snap["text"]


