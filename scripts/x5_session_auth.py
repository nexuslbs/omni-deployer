def host_omni():
    """Host path of the omni dir (the fixture is mounted from the host)."""
    cid = open("/etc/hostname", encoding="utf-8").read().strip()
    r = _sh("docker inspect -f '{{range .Mounts}}"
            "{{if eq .Destination \"/opt/omni\"}}{{.Source}}{{end}}{{end}}' " + cid)
    return (r.stdout or "").strip() or None


def fixture_dir():
    h = host_omni()
    if not h:
        return None
    d = f"{h}/data/playwright/{FIXTURE_NAME}"
    os.makedirs(d, exist_ok=True)
    for name, body in (("login.html", LOGIN_HTML), ("index.html", INDEX_HTML),
                       ("server.js", SERVER_JS)):
        with open(f"{d}/{name}", "w", encoding="utf-8") as fh:
            fh.write(body)
    return d


def fixture_up():
    """Start (or reuse) the fixture site on the bridge gateway. Returns bool."""
    d = fixture_dir()
    if not d:
        return False
    _sh("docker rm -f " + FIXTURE_NAME)
    r = _sh(f"docker run -d --name {FIXTURE_NAME} -p 172.17.0.1:{FIXTURE_PORT}:"
            f"{FIXTURE_PORT} -v {d}:/site:ro {NODE_IMAGE} node /site/server.js")
    if r.returncode != 0:
        print(f"  [fixture] docker run failed: {(r.stderr or r.stdout).strip()[:200]}")
        return False
    for _ in range(20):
        c = _sh(f"curl -s -o /dev/null -w '%{{http_code}}' "
                f"http://172.17.0.1:{FIXTURE_PORT}/login.html", timeout=15)
        if (c.stdout or "").strip() == "200":
            return True
        time.sleep(0.5)
    return False


def fixture_down():
    _sh("docker rm -f " + FIXTURE_NAME)
    h = host_omni()
    if h:
        _sh(f"rm -rf {h}/data/playwright/{FIXTURE_NAME}")


atexit.register(lambda: fixture_down())


